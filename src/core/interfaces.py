from typing import (
    Callable,
    Dict,
    List,
    Optional,
    Protocol,
    Tuple,
    runtime_checkable,
)

from src.core.dtos import AudioData, CacheEntry


@runtime_checkable
class IClipboard(Protocol):
    def read_text(self) -> str: ...
    def write_text(self, text: str) -> None: ...
    def read_file_paths(self) -> List[str]: ...


@runtime_checkable
class IAudioRecorder(Protocol):
    @property
    def device_sample_rate(self) -> int: ...
    def get_device_info(self) -> Optional[Dict]: ...
    def start_recording(self) -> None: ...
    def stop_recording(self) -> Optional[AudioData]: ...


@runtime_checkable
class ITranscriber(Protocol):
    @property
    def keep_model_loaded(self) -> bool: ...
    @keep_model_loaded.setter
    def keep_model_loaded(self, value: bool) -> None: ...
    @property
    def gpu_profile(self) -> str: ...
    def transcribe(self, audio: AudioData) -> str: ...
    def preload_for_recording(self) -> None: ...
    def set_gpu_profile(self, profile: str) -> None: ...
    def get_model_status(self) -> str: ...
    def shutdown(self) -> None: ...


@runtime_checkable
class IYouTubeDownloader(Protocol):
    def is_valid_url(self, url: str) -> bool: ...
    def download_audio(self, url: str) -> Optional[AudioData]: ...
    def cleanup(self) -> None: ...


@runtime_checkable
class ILocalFileProcessor(Protocol):
    def is_valid_path(self, path: str) -> bool: ...
    def process(self, path: str) -> Optional[AudioData]: ...
    def cleanup(self) -> None: ...


@runtime_checkable
class ICacheManager(Protocol):
    def get(self, key: str) -> Optional[CacheEntry]: ...
    def put(self, key: str, entry: CacheEntry) -> None: ...
    def delete(self, key: str) -> bool: ...
    def get_all(self) -> Dict[str, CacheEntry]: ...
    def shutdown(self) -> None: ...


@runtime_checkable
class IAppNotifier(Protocol):
    def update_status(self, status: str) -> None: ...


@runtime_checkable
class ITTSEngine(Protocol):
    @property
    def is_speaking(self) -> bool: ...
    def generate(self, text: str) -> Tuple[bytes, str]: ...
    def speak(self, text: str) -> None: ...
    def play_file(self, path: str) -> None: ...
    def stop(self) -> None: ...
    def shutdown(self) -> None: ...


@runtime_checkable
class ISummarizer(Protocol):
    def summarize(self, text: str, system_prompt: str = "") -> str: ...


@runtime_checkable
class IHotkeyManager(Protocol):
    def bind_shift(self, key_char: str, callback: Callable[[], None]) -> None: ...
    def start(self) -> None: ...
    def stop(self) -> None: ...
